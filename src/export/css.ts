import type { Theme } from "../model/theme";
import { validateTheme } from "../model/validate";

type Generic = "sans-serif" | "serif" | "monospace";

// Fallbacks for viewers who don't have the Power BI font (Segoe and DIN are the usual misses off Windows).
// Fonts not listed here are sans-serif.
const SERIF = new Set(["Cambria", "Constantia", "Georgia", "Times New Roman"]);
const MONO = new Set(["Consolas", "Courier New"]);

const SANS_FALLBACKS = ["system-ui", "-apple-system", '"Helvetica Neue"', "Arial"];

// Power BI's dropdown labels the weights "Segoe UI Light" and "Segoe (Bold)"; CSS only knows the family.
const cssFamily = (name: string) => (name === "Segoe (Bold)" ? "Segoe UI" : name);

function fontStack(name: string): string {
  const generic: Generic = SERIF.has(name) ? "serif" : MONO.has(name) ? "monospace" : "sans-serif";
  const fallbacks = generic === "sans-serif" ? SANS_FALLBACKS : [];
  return [`"${cssFamily(name)}"`, ...fallbacks, generic].join(", ");
}

/**
 * A global stylesheet for pages that embed or sit beside Power BI / Fabric content: design tokens as
 * custom properties on :root, plus rules built only from those tokens. Everything is prefixed
 * "feathers-" and the element rules are scoped under .feathers-root so the file can't restyle a host page
 * that didn't opt in.
 */
export function exportCss(theme: Theme): string {
  validateTheme(theme);
  const { palette, status, text, background, gridline, zeroline, visualBorder, fonts, sizes } = theme;

  const tokens: [string, string][] = [
    ...palette.categorical.map((c, i): [string, string] => [`cat-${i + 1}`, c]),
    ["seq-low", palette.sequential[0]],
    ["seq-high", palette.sequential[1]],
    ["div-low", palette.diverging[0]],
    ["div-mid", palette.diverging[1]],
    ["div-high", palette.diverging[2]],
    ["good", status.good],
    ["neutral", status.neutral],
    ["bad", status.bad],
    ["text-primary", text.primary],
    ["text-secondary", text.secondary],
    ["text-muted", text.muted],
    ["bg-canvas", background.canvas],
    ["bg-page", background.page],
    ["bg-container", background.container],
    ["gridline", gridline.color],
    ["zeroline", zeroline.color],
    // A hidden Power BI border becomes a transparent one so cards keep the same box size.
    ["border", visualBorder.visible ? visualBorder.color : "transparent"],
    ["font-body", fontStack(fonts.powerBi.body)],
    ["font-title", fontStack(fonts.powerBi.title)],
    ["size-body", `${sizes.body}pt`],
    ["size-title", `${sizes.title}pt`],
    ["size-callout", `${sizes.callout}pt`],
  ];
  const v = (name: string) => `var(--feathers-${name})`;

  const series = palette.categorical.map(
    (_, i) => `.feathers-series-${i + 1} { color: ${v(`cat-${i + 1}`)}; }`,
  );

  return [
    `/* ${theme.name.replace(/\*\//g, "* /")}: generated by Feathers. Link this file, then add class="feathers-root" to the element that wraps your content. */`,
    ":root {",
    ...tokens.map(([name, value]) => `  --feathers-${name}: ${value};`),
    "}",
    "",
    ".feathers-canvas {",
    `  background: ${v("bg-canvas")};`,
    "}",
    "",
    ".feathers-root {",
    `  background: ${v("bg-page")};`,
    `  color: ${v("text-primary")};`,
    `  font-family: ${v("font-body")};`,
    `  font-size: ${v("size-body")};`,
    "  line-height: 1.5;",
    "}",
    "",
    ".feathers-root h1, .feathers-root h2, .feathers-root h3 {",
    `  font-family: ${v("font-title")};`,
    `  color: ${v("text-primary")};`,
    "}",
    "",
    `.feathers-root h1 { font-size: ${v("size-title")}; }`,
    "",
    ".feathers-root a {",
    `  color: ${v("cat-1")};`,
    "}",
    "",
    ".feathers-card {",
    `  background: ${v("bg-container")};`,
    `  border: 1px solid ${v("border")};`,
    `  color: ${v("text-primary")};`,
    "  padding: 1rem;",
    "}",
    "",
    ".feathers-card-title {",
    `  font-family: ${v("font-title")};`,
    `  font-size: ${v("size-title")};`,
    "  margin: 0 0 0.5rem;",
    "}",
    "",
    ".feathers-kpi {",
    `  font-family: ${v("font-title")};`,
    `  font-size: ${v("size-callout")};`,
    `  color: ${v("cat-1")};`,
    "}",
    "",
    ".feathers-label {",
    `  color: ${v("text-secondary")};`,
    "}",
    "",
    ".feathers-muted {",
    `  color: ${v("text-muted")};`,
    "}",
    "",
    ".feathers-table {",
    "  border-collapse: collapse;",
    "  width: 100%;",
    "}",
    "",
    ".feathers-table th, .feathers-table td {",
    `  border-bottom: 1px solid ${v("gridline")};`,
    "  padding: 0.4rem 0.75rem;",
    "  text-align: left;",
    "}",
    "",
    ".feathers-table th {",
    `  color: ${v("text-secondary")};`,
    "}",
    "",
    `.feathers-good { color: ${v("good")}; }`,
    `.feathers-neutral { color: ${v("neutral")}; }`,
    `.feathers-bad { color: ${v("bad")}; }`,
    "",
    ...series,
    "",
  ].join("\n");
}
